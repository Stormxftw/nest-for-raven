/* Fixed hierarchy and conversation checks. Example only; no gateway/model calls. */
async (page) => {
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  const assert = (condition, message) => { if (!condition) throw new Error(message); };
  const positions = () => page.locator('.react-flow__node').evaluateAll(nodes => Object.fromEntries(nodes.map(node => [node.dataset.id, node.style.transform])));
  const build = page.getByRole('group', {name:/Build the first experience,/});
  await page.setViewportSize({width:1440,height:960});
  await page.reload();
  await build.click();
  await page.getByRole('tabpanel', {name:'Properties',exact:true}).getByText('Define the visual language', {exact:true}).waitFor();
  const before = await positions();
  const box = await build.boundingBox();
  await page.mouse.move(box.x + box.width / 2, box.y + 20);
  await page.mouse.down();
  for (let i=1;i<=12;i++) {
    await page.mouse.move(box.x + box.width / 2 - i*3, box.y+20-i*2);
    assert(await build.locator('.orbit-node').evaluate(el => getComputedStyle(el).opacity === '1' && getComputedStyle(el).transform === 'none'), 'Card flickered or moved during pointer drag');
  }
  await page.mouse.up();
  assert(JSON.stringify(await positions()) === JSON.stringify(before), 'Dragging changed the fixed hierarchy');
  await page.getByRole('button', {name:'Replay step 1/4',exact:true}).click();
  await page.getByRole('tabpanel', {name:'Properties',exact:true}).getByText('Complete', {exact:true}).waitFor();
  assert(JSON.stringify(await positions()) === JSON.stringify(before), 'Status update changed the hierarchy');
  await page.getByRole('textbox', {name:'Message to Raven'}).fill('Draft while inspecting the chart');
  assert(JSON.stringify(await positions()) === JSON.stringify(before), 'Typing changed the hierarchy');
  await build.focus();
  await page.keyboard.press('ArrowRight');
  await page.keyboard.press('Delete');
  assert(JSON.stringify(await positions()) === JSON.stringify(before), 'Keyboard moved or removed a task');
  assert(await page.getByRole('button', {name:'Reset node positions',exact:true}).count() === 0, 'Obsolete arrangement control remains');
  assert(await page.locator('.react-flow__edge.animated').count() === 0, 'Travelling edges remain');
  await page.getByRole('button', {name:'Scroll to mission host',exact:true}).click();
  assert(await page.locator('.mission-map').evaluate(el => el.scrollTop) === 0, 'Return to host did not scroll to top');
  await page.getByRole('button', {name:'Expand task map',exact:true}).click();
  assert(!(await page.getByRole('region', {name:'Conversation',exact:true}).isVisible()), 'Chart did not expand');
  await page.screenshot({path:'output/playwright/parchment-expanded.png'});
  await page.getByRole('button', {name:'Talk to selected agent',exact:true}).click();
  await page.getByRole('button', {name:'Back to host',exact:true}).waitFor();
  assert(await page.getByRole('region', {name:'Conversation',exact:true}).isVisible(), 'Talk did not restore conversation');
  await page.getByRole('button', {name:'Back to host',exact:true}).click();
  assert(await page.getByRole('textbox', {name:'Message to Raven'}).inputValue() === 'Draft while inspecting the chart', 'Host draft lost');
  await page.getByRole('textbox', {name:'Message to Raven'}).fill('');
  await page.getByRole('tab', {name:'Output',exact:true}).click();
  await page.getByRole('tabpanel').getByText('Example work log', {exact:false}).waitFor();
  await page.getByRole('tab', {name:'Prompt',exact:true}).click();
  await page.getByRole('tabpanel').getByText('Build the note capture', {exact:false}).waitFor();
  await page.getByRole('tab', {name:'Files 2',exact:true}).click();
  await page.getByRole('tabpanel').getByText('src/App.tsx', {exact:true}).waitFor();
  await page.getByRole('tab', {name:'Properties',exact:true}).click();
  await page.getByRole('button', {name:'design',exact:true}).click();
  await page.getByRole('tabpanel').getByText('Understand the audience', {exact:true}).waitFor();
  await build.click();
  const typography = await page.locator('.message-text').first().evaluate(el => ({size:getComputedStyle(el).fontSize, font:getComputedStyle(el).fontFamily, color:getComputedStyle(el).color}));
  assert(parseFloat(typography.size) >= 16 && !typography.font.includes('DM Sans'), 'Conversation type regression');
  await page.getByRole('button', {name:'Scroll to mission host',exact:true}).click();
  await page.screenshot({path:'output/playwright/parchment-desktop.png'});
  await page.setViewportSize({width:390,height:844});
  assert(!(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)), 'Mobile horizontal page overflow');
  await page.screenshot({path:'output/playwright/parchment-mobile.png'});
  await page.getByRole('button', {name:'Show team map',exact:true}).click();
  await page.getByRole('region', {name:'Task hierarchy',exact:true}).waitFor();
  await page.waitForFunction(() => {const el=document.querySelector('.mission-map');return el.scrollWidth <= el.clientWidth;});
  const phone = await page.locator('.mission-map').evaluate(el => ({width:el.clientWidth,scrollWidth:el.scrollWidth,height:el.clientHeight,scrollHeight:el.scrollHeight}));
  assert(phone.scrollHeight > phone.height, 'Phone chart should scroll at a readable size');
  await build.click();
  assert(await build.locator('strong').evaluate(el => parseFloat(getComputedStyle(el).fontSize)) >= 14, 'Chart labels too small');
  const viewport = await page.locator('.react-flow__viewport').evaluate(el => el.style.transform);
  assert(viewport.includes('scale(1)'), 'Chart was scaled to unreadable text');
  await page.screenshot({path:'output/playwright/parchment-mobile-map.png'});
  await page.getByRole('button', {name:'Talk to selected agent',exact:true}).click();
  assert(await page.getByRole('textbox', {name:'Message to Raven'}).isVisible(), 'Mobile Talk did not restore composer');
  await page.getByRole('button', {name:'Back to host',exact:true}).click();
  await page.setViewportSize({width:1366,height:768});
  await page.getByRole('button', {name:'Show team map',exact:true}).click();
  await page.getByRole('group', {name:/Check the finished flow,/}).click();
  await page.getByRole('tabpanel').getByText('Queued', {exact:true}).waitFor();
  assert(!(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)), 'Laptop overflow');
  await page.screenshot({path:'output/playwright/parchment-laptop.png'});
  assert(errors.length === 0, `Browser errors: ${errors.join('; ')}`);
  return {result:'PASS: fixed pointer/keyboard positions, stable status/draft updates, full-size scrollable hierarchy, no moving connectors, properties/dependencies/tabs, expanded Talk, draft preservation, desktop/laptop/phone.', typography, phone, errors};
}
